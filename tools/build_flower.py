"""Regenerate word-flower/words.js.

Answer words come from SCOWL (via the `wordlist-english` npm package), sizes
10-35 that are also reasonably frequent in everyday English (wordfreq), minus
tools/flower_blocklist.txt. Other real words (up to SCOWL size 70) are accepted as
bonus words. Puzzles never use the letter S (it would allow easy plurals).

A puzzle is the 7 distinct letters of a familiar word, plus a required center
letter, kept only if it has a comfortable number of familiar answers.

Setup:
    pip install wordfreq
    npm install wordlist-english

Run from the repo root:
    python3 tools/build_flower.py path/to/node_modules/wordlist-english
"""

import json
import os
import random
import sys

from wordfreq import zipf_frequency

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
LEVELS = (10, 20, 35, 40, 50, 55, 60, 70)
MIN_ZIPF = 2.0  # answer words must be at least this common (drops "hided", "geeing")


def words_up_to(base, max_level):
    out = set()
    for n in LEVELS:
        if n > max_level:
            break
        for variant in ("english", "american"):
            out |= set(json.load(open(os.path.join(base, f"{variant}-words-{n}.json"))))
    return {w for w in out
            if w.isascii() and w.isalpha() and w.islower()
            and len(w) >= 4 and "s" not in w and len(set(w)) <= 7}


def points(w):
    return (1 if len(w) == 4 else len(w)) + (7 if len(set(w)) == 7 else 0)


def main(base):
    block = set(open(os.path.join(HERE, "flower_blocklist.txt")).read().split())
    common = {w for w in words_up_to(base, 35) - block if zipf_frequency(w, "en") >= MIN_ZIPF}
    real = words_up_to(base, 70) - common - block

    letter_sets = sorted({frozenset(w) for w in common
                          if len(set(w)) == 7 and zipf_frequency(w, "en") >= 3.0},
                         key=lambda s: "".join(sorted(s)))
    puzzles = []
    for letters in letter_sets:
        candidates = [w for w in common if set(w) <= letters]
        for center in sorted(letters):
            answers = [w for w in candidates if center in w]
            if not 20 <= len(answers) <= 45:
                continue
            if sum(points(w) for w in answers) > 200:
                continue
            familiarity = sum(zipf_frequency(w, "en") for w in answers) / len(answers)
            if familiarity < 3.3:
                continue
            puzzles.append("".join(sorted(letters)) + center)
    random.Random(2026).shuffle(puzzles)
    print(f"{len(puzzles)} puzzles, {len(common)} answer words, {len(real)} bonus words")

    with open(os.path.join(ROOT, "word-flower", "words.js"), "w") as f:
        f.write("// Generated by tools/build_flower.py. Do not edit by hand.\n")
        f.write("// Each puzzle is 7 letters followed by the center letter.\n")
        f.write("window.FLOWER_DATA = {\n")
        f.write(f'  puzzles: "{" ".join(puzzles)}",\n')
        f.write(f'  common: "{" ".join(sorted(common))}",\n')
        f.write(f'  real: "{" ".join(sorted(real))}"\n')
        f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "node_modules/wordlist-english")
