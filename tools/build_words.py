"""Regenerate word-guess/words.js.

Answers are common, familiar words: frequent in everyday English (per the
`wordfreq` package), in the dictionary, not simple plurals or -ed forms, and not
in tools/blocklist.txt (names, places, slang, rude or grim words).
Allowed guesses are every dictionary word of that length.

Setup:
    pip install wordfreq
    npm install word-list@2        # provides node_modules/word-list/words.txt

Run from the repo root:
    python3 tools/build_words.py path/to/node_modules/word-list/words.txt
"""

import os
import sys

from wordfreq import top_n_list, zipf_frequency

# Minimum everyday-use frequency (Zipf scale) for an answer word, per length.
MIN_ZIPF = {4: 3.45, 5: 3.25}

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)


def main(dict_path):
    words = set(open(dict_path).read().split())
    block = set(open(os.path.join(HERE, "blocklist.txt")).read().split())
    top = top_n_list("en", 60000)

    out = {}
    for length, min_zipf in MIN_ZIPF.items():
        allowed = sorted(w for w in words if len(w) == length and w.isascii() and w.isalpha())
        answers = []
        for w in top:
            if len(w) != length or not (w.isascii() and w.isalpha()):
                continue
            if w not in words or w in block or zipf_frequency(w, "en") < min_zipf:
                continue
            if w.endswith("s") and not w.endswith("ss") and w[:-1] in words:
                continue  # simple plural
            if w.endswith("ed") and (w[:-2] in words or w[:-1] in words):
                continue  # simple past tense
            answers.append(w)
        out[length] = (sorted(answers), allowed)
        print(f"{length} letters: {len(answers)} answers, {len(allowed)} allowed guesses")

    with open(os.path.join(ROOT, "word-guess", "words.js"), "w") as f:
        f.write("// Generated by tools/build_words.py. Do not edit by hand.\n")
        f.write("window.WORD_LISTS = {\n")
        for length, (answers, allowed) in out.items():
            f.write(f"  {length}: {{\n")
            f.write(f'    answers: "{" ".join(answers)}",\n')
            f.write(f'    allowed: "{" ".join(allowed)}"\n')
            f.write("  },\n")
        f.write("};\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "node_modules/word-list/words.txt")
